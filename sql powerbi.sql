# using a CTE ,classify products into perfomance categories based on their total sales #
with product_categories as (
	select p.pid,p.product,sum(amount) as total_sales 
    from sales s
    join products p on p.pid = s.pid
    group by p.pid,p.product
)
select * ,
	case when  total_sales >2000000 then 'high performance'
         when  total_sales >1000000 then 'medium performance'
         when total_sales >10000 then 'low performance'
         else 'very low performance'
    end as product_performance
from product_categories ;    

